"""
Named comps for a hand-checkable set of 2025 targets: every method's top 10 same-role comps.

Targets (~20):
    - well-known pitchers the author can check against tjstats.ca (the fidelity check), plus the
      two he flagged in the June sample (Crochet, Castillo);
    - the pitchers where TJStats and the learned embedding disagree most (smallest overlap of their
      top-10 lists): the error-analysis cases.
For each target, and each method (raw Euclidean, TJStats, HZB, SEAM, learned): the top 10 comps from
the same season, hand, and role (>= 300 pitches), with primary-fastball velo, arm angle, top 3
pitches by usage, role, and actual RV/100.

Pipeline stage 5 of 7 (comps report). Stages: fetch -> features -> train -> evaluate -> comps report ->
app tables -> app.

Inputs:  pitcher_seasons / arsenal_pitch_type / pitches (build_arsenal.py), models/embeddings_t1.parquet
Outputs: docs/results/comps_2025.md (--sample: models/sample/results/comps_2025.md)

Usage (from the repo root):
    python -m src.eval.comps_report [--sample]

AI assistance: drafted with Claude Code (Anthropic); reviewed, run, and modified by
Toma Shigaki-Than. See ATTRIBUTION.md.
"""
from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from typing import Dict, List

import numpy as np
import pandas as pd

from src.eval.retrieval import K_NEIGHBORS, candidate_pool, eligible
from src.eval.run_eval import BASE_METHODS, LABELS, season_table, similarity_suite
from src.models.hzb_similarity import load_pitches
from src.models.train_embedding import Paths

YEAR = 2025  # why (D5): a report to read and inspect, so it uses 2025; 2026 is only ever scored once
# Well-known pitchers for the tjstats.ca fidelity check, then the two flagged in the June sample.
NAMED = ["Skubal, Tarik", "Skenes, Paul", "Wheeler, Zack", "Webb, Logan", "Clase, Emmanuel",
         "Crochet, Garrett", "Castillo, Luis"]
N_DISAGREE = 13  # the 7 named pitchers + 13 biggest disagreements = the ~20 targets


def fold(name: str) -> str:
    """Lowercase, accents removed, for name matching."""
    return unicodedata.normalize("NFKD", str(name)).encode("ascii", "ignore").decode().lower()


def top_pitches(by_type: pd.DataFrame, year: int) -> pd.Series:
    """'FF 45 · SL 30 · CH 15' (percent of all pitches) per (pitcher, p_throws)."""
    t = by_type[by_type["game_year"] == year].sort_values("usage", ascending=False)
    t = t.groupby(["pitcher", "p_throws"]).head(3)
    label = t["pitch_type"] + " " + (100 * t["usage"]).round().astype(int).astype(str)
    return label.groupby([t["pitcher"], t["p_throws"]]).agg(" · ".join)


def anchor(name: str) -> str:
    """GitHub's heading anchor: lowercase, punctuation dropped, spaces to hyphens (accents kept)."""
    return re.sub(r"[^\w\- ]", "", name.lower()).replace(" ", "-")


def describe(ps: pd.DataFrame, i: int, pitches: pd.Series) -> Dict[str, str]:
    r = ps.iloc[i]
    return {"name": r["player_name"], "role": r["role"], "fb": f"{r['fb_velo']:.1f} ({r['fb_type']})" if pd.notna(r["fb_velo"]) else "–",
            "arm": f"{r['arm_angle']:.0f}°" if pd.notna(r["arm_angle"]) else "–",
            "pitches": pitches.get((r["pitcher"], r["p_throws"]), "–"), "rv": f"{r['pitcher_rv100']:+.2f}"}


def comps(ps: pd.DataFrame, sim: np.ndarray, i: int, ok: np.ndarray) -> np.ndarray:
    cand = candidate_pool(ps, i, ok)
    return cand[np.argsort(-sim[i, cand], kind="stable")[:K_NEIGHBORS]]


def pick_targets(ps: pd.DataFrame, sims: Dict[str, np.ndarray]) -> List[tuple]:
    """(row, reason) for named pitchers present, then the biggest TJStats-vs-learned disagreements."""
    ok = eligible(ps)
    folded = ps["player_name"].map(fold)
    chosen, rows = [], set()
    for name in NAMED:
        hit = np.flatnonzero(ok & (folded == fold(name)).to_numpy())
        if len(hit):
            chosen.append((int(hit[0]), "fidelity check vs. tjstats.ca" if name not in NAMED[-2:] else "flagged in the June sample"))
            rows.add(int(hit[0]))
    overlap = []
    for i in np.flatnonzero(ok):
        if i in rows or len(candidate_pool(ps, i, ok)) < K_NEIGHBORS:
            continue
        a, b = set(comps(ps, sims["tjstats"], i, ok)), set(comps(ps, sims["learned"], i, ok))
        overlap.append((len(a & b), i))
    for n_shared, i in sorted(overlap)[:N_DISAGREE]:
        chosen.append((int(i), f"TJStats and learned top 10 share {n_shared} of 10"))
    return chosen


def render(ps: pd.DataFrame, sims: Dict[str, np.ndarray], targets: List[tuple], pitches: pd.Series,
           twins: pd.DataFrame) -> str:
    ok = eligible(ps)
    lines = [
        f"# Comps report, {YEAR}",
        "",
        "Generated by `src/eval/comps_report.py`. Every comp is from the same season, throwing hand, and role "
        "(SP = started at least half his games), with at least 300 pitches. Similarity itself never sees role (D23).",
        "TJStats, HZB, and SEAM are published formulas run on our Savant data (D4, D26, D27). TJStats follows the "
        "tool's defaults with its kernel width fitted to tjstats.ca (`docs/results/tjstats_fidelity_*.csv`); the "
        "site has no role filter or 300-pitch floor, so these same-role lists can differ from its top 20.",
        "",
        "Columns: primary fastball velo (mph, type) · average arm angle · top 3 pitches (% of all pitches) · actual RV/100 "
        "(runs saved per 100 pitches; positive = better).",
        "",
        "## Targets",
        "",
    ]
    for i, why in targets:
        d = describe(ps, i, pitches)
        lines.append(f"- [{d['name']}](#{anchor(d['name'])}) ({ps.iloc[i]['p_throws']}HP {d['role']}): {why}")
    for i, why in targets:
        d = describe(ps, i, pitches)
        lines += ["", f"## {d['name']}",
                  "", f"{ps.iloc[i]['p_throws']}HP {d['role']} · FB {d['fb']} · arm {d['arm']} · {d['pitches']} · "
                      f"RV/100 {d['rv']} · *{why}*", ""]
        for m in BASE_METHODS:
            lines += [f"**{LABELS[m]}**", "", "| # | comp | role | FB | arm | top 3 pitches | RV/100 |",
                      "|---|---|---|---|---|---|---|"]
            for rank, j in enumerate(comps(ps, sims[m], i, ok), 1):
                c = describe(ps, j, pitches)
                lines.append(f"| {rank} | {c['name']} | {c['role']} | {c['fb']} | {c['arm']} | {c['pitches']} | {c['rv']} |")
            lines.append("")
    if len(twins):
        lines += ["## Physical twins, functional strangers (and the reverse)", "",
                  "Pairs one method ranks in the top 3 while the other puts them in the bottom half of the pool. "
                  "From `twins_val.csv`; the ten with the largest RV/100 gap per kind.", ""]
        for kind, g in twins.groupby("kind"):
            lines += [f"**{kind}**", "", "| query | comp | TJStats pct | learned pct | FB (q / c) | RV/100 (q / c) |",
                      "|---|---|---|---|---|---|"]
            for r in g.sort_values("absdiff_pitcher_rv100", ascending=False).head(10).itertuples():
                lines.append(f"| {r.query} | {r.comp} | {r.tjstats_pct:.2f} | {r.learned_pct:.2f} | "
                             f"{r.query_fb_velo:.1f} / {r.comp_fb_velo:.1f} | {r.query_pitcher_rv100:+.2f} / {r.comp_pitcher_rv100:+.2f} |")
            lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Named comps for ~20 targets, every method.")
    ap.add_argument("--sample", action="store_true")
    args = ap.parse_args()
    paths = Paths.make(args.sample)
    seasons = pd.read_parquet(paths.data / "pitcher_seasons.parquet")
    by_type = pd.read_parquet(paths.data / "arsenal_pitch_type.parquet")
    embs = {"learned": pd.read_parquet(paths.models / "embeddings_t1.parquet")}
    ps = season_table(seasons, YEAR)
    sims = similarity_suite(ps, by_type, load_pitches(paths.data, YEAR), embs, YEAR)
    targets = pick_targets(ps, sims)
    twins_path = paths.results / "twins_val.csv"
    twins = pd.read_csv(twins_path) if twins_path.exists() else pd.DataFrame()
    out = paths.results / f"comps_{YEAR}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(ps, sims, targets, top_pitches(by_type, YEAR), twins))
    print(f"[comps] {len(targets)} targets ({sum(1 for _, w in targets if 'share' not in w)} named) -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
